/**
 * Names for the background sky.
 *
 * Three rules shape this file:
 *
 * 1. **Only real objects.** Every entry is a star that exists, under an
 *    identifier it actually carries. Nothing here is invented, which is why the
 *    list is finite and the starfield labels a subset of its points rather than
 *    all of them.
 * 2. **No repeats.** Finding the same star twice in one sky would read as a
 *    bug, so each hoverable point takes a distinct slot from this pool.
 * 3. **Familiar names first, and at least as many of them.** Proper names lead
 *    the tooltip and the catalogue list is capped at the length of the named
 *    list, so the sky answers with Kochab more often than with a survey number.
 *
 * Objects with several identifiers keep them all: Kepler-452 is also
 * KIC 8311864 and KOI-7016, and the tooltip shows the common name first.
 */

/** One object, as it is known across catalogues. */
