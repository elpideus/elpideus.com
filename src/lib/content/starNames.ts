/** Everything a background star can be called. */
const POOL: readonly StarDesignation[] = [...CURATED, ...CATALOGUED];

/**
 * How many points the sky can label without repeating itself. The starfield
 * makes exactly this many of its points hoverable.
 */
export const SKY_DESIGNATION_COUNT = POOL.length;

/**
 * Deterministic shuffle, so neighbouring points in a buffer do not end up with
 * neighbouring entries from the list, and so named stars and catalogue numbers
 * are mixed evenly across the sky. Fixed seed: the sky reads the same on every
 * visit.
 */
const ORDER: readonly number[] = (() => {
  const order = POOL.map((_, index) => index);
  let seed = 0x9e3779b9;
  for (let index = order.length - 1; index > 0; index -= 1) {
    seed = (seed * 1664525 + 1013904223) >>> 0;
    const swap = seed % (index + 1);
    const held = order[index];
    order[index] = order[swap];
    order[swap] = held;
  }
  return order;
})();

/**
 * The designation for a point's slot.
 *
 * One slot per hoverable point, never more slots than the pool holds, so no two
 * points can carry the same name.
 */
export function designationForSlot(slot: number): StarDesignation | null {
  if (slot < 0 || slot >= ORDER.length) return null;
  return POOL[ORDER[slot]];
}
